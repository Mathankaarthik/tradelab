import { useApp } from '../store/AppContext';
import { fmtClock, fmtDate, fmtDow, marketStatus, minuteOfDay, OPEN_MIN } from '../utils/marketTime';

const SPEEDS = [0.5, 1, 2, 5, 10];

export default function MarketBar() {
  const { state, engine, running, start, pause, nextTick, setSpeed, nudge, jump, skipToOpen, nextDay } = useApp();
  const st = marketStatus(engine.time);
  const over = engine.isDayOver();
  const pre = minuteOfDay(engine.time) < OPEN_MIN;
  return (
    <div className="flex items-center gap-3 overflow-x-auto whitespace-nowrap border-b border-line bg-app px-3 py-1.5 text-[12px]" role="toolbar" aria-label="Simulation controls">
      <div className="flex items-center gap-2" aria-live="polite">
        <span className={`h-2 w-2 rounded-full ${st.open ? 'bg-gain' : 'bg-loss'}`} aria-hidden="true" />
        <span className={`font-semibold ${st.open ? 'text-gain' : 'text-loss'}`}>{st.label}</span>
        <span className="text-mute">{st.detail}</span>
      </div>
      <div className="text-mute" title="Simulated clock (IST). It only moves when the market is running.">
        {fmtDow(engine.time)}, {fmtDate(engine.time)} <b className="ml-1 text-ink">{fmtClock(engine.time)}</b>
      </div>
      <span className="h-4 w-px bg-line" aria-hidden="true" />
      <div className="flex items-center gap-1" data-tour="sim">
        {running
          ? <button className="btn btn-sm" onClick={pause} aria-label="Pause market">⏸ Pause</button>
          : <button className="btn btn-sm btn-buy" onClick={start} disabled={over} aria-label="Start market">▶ Start Market</button>}
        <button className="btn btn-sm" onClick={nextTick} disabled={over} title="Advance 5 simulated seconds">Next tick</button>
        <div className="flex items-center rounded border border-line" role="group" aria-label="Speed">
          <span className="px-1.5 text-mute">⏩</span>
          {SPEEDS.map((s) => (
            <button key={s} aria-pressed={state.settings.speed === s} onClick={() => setSpeed(s)}
              className={`px-1.5 py-1 ${state.settings.speed === s ? 'bg-buy text-white' : 'text-mute hover:text-ink'}`}>{s}x</button>
          ))}
        </div>
      </div>
      <span className="h-4 w-px bg-line" aria-hidden="true" />
      <div className="flex items-center gap-1" role="group" aria-label={`Nudge ${state.selected} price`}>
        <span className="text-mute" title="Manually move the selected stock to test stop-loss and target orders">Nudge {state.selected}</span>
        {[-1, -0.5, 0.5, 1].map((d) => (
          <button key={d} className="btn btn-sm" onClick={() => nudge(d)} aria-label={`Move price ${d > 0 ? 'up' : 'down'} by ${Math.abs(d)} rupee`}>{d > 0 ? '+' : '-'}₹{Math.abs(d)}</button>
        ))}
      </div>
      <span className="h-4 w-px bg-line" aria-hidden="true" />
      <div className="flex items-center gap-1" role="group" aria-label="Practice mode time controls">
        <span className="text-mute" title="Practice mode: accelerate time">Practice</span>
        {pre && <button className="btn btn-sm" onClick={skipToOpen}>Skip to 9:15</button>}
        <button className="btn btn-sm" onClick={() => jump(15)} disabled={over}>+15m</button>
        <button className="btn btn-sm" onClick={() => jump(60)} disabled={over}>+1h</button>
        <button className="btn btn-sm" onClick={() => jump(375)} disabled={over}>To close</button>
        {over && <button className="btn btn-sm btn-buy" onClick={nextDay}>Next trading day</button>}
      </div>
      <span className="ml-auto chip border-warn/40 text-warn" title="Prices are generated by a toy random model. They are not real quotes.">SIMULATED MARKET DATA</span>
    </div>
  );
}

import { useEffect, useLayoutEffect, useState } from 'react';
import { useApp } from '../store/AppContext';

const STEPS = [
  { target: 'balance', tab: 'chart', title: 'Your virtual balance', text: 'This is your virtual balance. You start with ₹1,00,000 of pretend money. Nothing here is real.' },
  { target: 'price', tab: 'chart', title: 'The stock price', text: 'This is the stock price. It is generated by a simulation and moves when you press ▶ Start Market.' },
  { target: 'buy', tab: 'chart', title: 'BUY', text: 'BUY means you expect the price to rise. Press it, enter a quantity and place your first order.' },
  { target: 'pnl', tab: 'portfolio', title: 'Profit and loss', text: 'Your P&L changes as the simulated price moves. Green is profit, red is loss.' },
  { target: 'close', tab: 'portfolio', title: 'Close with SELL', text: 'SELL closes your position. The Close position button does it for you at the market price.' },
] as const;

function findVisible(name: string): HTMLElement | null {
  for (const el of Array.from(document.querySelectorAll<HTMLElement>(`[data-tour="${name}"]`))) {
    const r = el.getBoundingClientRect(); if (r.width > 0 && r.height > 0) return el;
  }
  return null;
}

export default function Tutorial() {
  const { endTutorial, setMobileTab, setBottomTab, setView } = useApp();
  const [i, setI] = useState(0); const [rect, setRect] = useState<DOMRect | null>(null);
  const step = STEPS[i];
  useEffect(() => { setView('terminal'); setMobileTab(step.tab); setBottomTab('positions'); }, [i, step.tab, setView, setMobileTab, setBottomTab]);
  useLayoutEffect(() => {
    const measure = () => { const el = findVisible(step.target); setRect(el ? el.getBoundingClientRect() : null); };
    const t = setTimeout(measure, 60); window.addEventListener('resize', measure); return () => { clearTimeout(t); window.removeEventListener('resize', measure); };
  }, [i, step.target]);
  useEffect(() => { const k = (e: KeyboardEvent) => { if (e.key === 'Escape') endTutorial(); }; document.addEventListener('keydown', k); return () => document.removeEventListener('keydown', k); }, [endTutorial]);
  const W = Math.min(320, window.innerWidth - 24);
  let style: React.CSSProperties = { left: (window.innerWidth - W) / 2, top: window.innerHeight / 2 - 90, width: W };
  if (rect) {
    const below = rect.bottom + 12 + 170 < window.innerHeight;
    style = { width: W, left: Math.min(Math.max(12, rect.left), window.innerWidth - W - 12), top: below ? rect.bottom + 12 : Math.max(12, rect.top - 12 - 170) };
  }
  return (
    <div className="fixed inset-0 z-[90]" role="dialog" aria-modal="true" aria-label="Guided tutorial">
      {rect ? <div className="pointer-events-none absolute rounded ring-2 ring-buy" style={{ left: rect.left - 4, top: rect.top - 4, width: rect.width + 8, height: rect.height + 8, boxShadow: '0 0 0 9999px rgba(0,0,0,.65)' }} /> : <div className="absolute inset-0 bg-black/65" />}
      <div className="absolute rounded-lg border border-line bg-panel p-4 shadow-2xl" style={style}>
        <div className="mb-1 text-[11px] text-mute">Step {i + 1} of {STEPS.length}</div>
        <h2 className="text-[15px] font-semibold">{step.title}</h2>
        <p className="mt-1 text-[13px] leading-snug">{step.text}</p>
        <div className="mt-3 flex items-center justify-between">
          <button className="btn btn-ghost btn-sm" onClick={endTutorial}>Skip Tutorial</button>
          <div className="flex gap-2">
            {i > 0 && <button className="btn btn-sm" onClick={() => setI(i - 1)}>Back</button>}
            <button data-autofocus autoFocus className="btn btn-buy btn-sm" onClick={() => (i === STEPS.length - 1 ? endTutorial() : setI(i + 1))}>{i === STEPS.length - 1 ? 'Start practicing' : 'Next'}</button>
          </div>
        </div>
      </div>
    </div>
  );
}
